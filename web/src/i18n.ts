const DICT = { en, th }
const saved = (() => { try { return localStorage.getItem('lang') } catch { return null } })()
// live ESM bindings: every importer reads the current language; useLang() at the root re-renders the tree on a switch
export let lang: Lang = saved === 'en' || saved === 'th' ? saved : navigator.language.startsWith('th') ? 'th' : 'en'
export let T = DICT[lang]
document.documentElement.lang = lang

const subs = new Set<() => void>()
export function setLang(l: Lang) {
  lang = l
  T = DICT[l]
  document.documentElement.lang = l
  try { localStorage.setItem('lang', l) } catch { /* private window: the choice lasts this visit */ }
  subs.forEach(f => f())
}
export const useLang = () => useSyncExternalStore(f => { subs.add(f); return () => subs.delete(f) }, () => lang)
